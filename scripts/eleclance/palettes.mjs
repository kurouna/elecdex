// ELECLANCE's palettes (docs/elec16-eleclance.md): sixteen colours each, every value a multiple
// of 8 so it is exactly an RGB555 colour. Colour 0 is the clear one. The order is the rows of
// art/palettes.png and the game's PAL_ constants; which slot a palette goes in is the game's.

const hex = (s) => {
  const v = Number.parseInt(s.slice(1), 16)
  return [(v >> 16) & 0xf8, (v >> 8) & 0xf8, v & 0xf8]
}
const row = (...colours) => colours.map(hex)

