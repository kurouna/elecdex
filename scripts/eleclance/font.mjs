/** `text` palette indices: the dark edge, then the letter's ramp from its foot to its head. */
const EDGE = 1
const RAMP = [4, 5, 6, 6, 6, 5, 4]

/** The 64 characters, each 8x8. */
export function fontFrames() {
  const out = []
  for (let code = 32; code < 96; code++) {
    const rows = GLYPHS[String.fromCharCode(code)] ?? []
    const c = new Canvas(8, 8)
    // The edge first, a point down and right of every point of the letter.
    rows.forEach((row, y) => {
      ;[...row].forEach((ch, x) => {
        if (ch !== '#') return
        for (const [dx, dy] of [
          [1, 1],
          [2, 1],
          [2, 0],
          [1, 0],
          [0, 1],
        ])
          c.set(x + dx, y + dy, EDGE)
      })
    })
    rows.forEach((row, y) => {
      ;[...row].forEach((ch, x) => {
        if (ch !== '#') return
        c.set(x, y, RAMP[y] ?? 6)
        c.set(x + 1, y, RAMP[y] ?? 6)
      })
    })
    out.push(c)
  }
  return out
}
