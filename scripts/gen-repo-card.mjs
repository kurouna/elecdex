/**
 * Generates public/elecdex_repo_card.svg, the banner at the top of the README.
 *
 * Laid out like the other elec series cards (elecxzy_repo_card.svg): the app icon
 * on the left, the name, a one-line description, feature pills and the repository
 * address, on white with two pale circles in the corner. Text is outlined to
 * paths from Source Sans 3 (SIL OFL 1.1), so the card looks the same wherever the
 * SVG is shown - GitHub renders it as an image, with no web fonts.
 *
 * The icon is embedded from build/icon.svg, so the card follows the icon.
 *
 * Run with: npm run gen:card
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import opentype from 'opentype.js'

const require = createRequire(import.meta.url)
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

const font = (weight) =>
  opentype.parse(
    readFileSync(
      require.resolve(`@fontsource/source-sans-3/files/source-sans-3-latin-${weight}-normal.woff`),
    ).buffer,
  )
const bold = font(700)
const semibold = font(600)

const SLATE_600 = '#475569'
const SLATE_400 = '#94a3b8'
const SKY_700 = '#0284c7'

/**
 * Lays glyphs out by advance width and pair kerning. opentype.js's own shaper
 * trips over this font's contextual substitution tables, and plain Latin text
 * needs none of them.
 */
function glyphRun(face, value, size) {
  const scale = size / face.unitsPerEm
  const glyphs = [...value].map((ch) => face.charToGlyph(ch))
  const positions = []
  let pen = 0
  glyphs.forEach((glyph, i) => {
    positions.push(pen)
    pen += glyph.advanceWidth * scale
    const next = glyphs[i + 1]
    const kern = next ? face.getKerningValue(glyph, next) : 0
    // Some pairs come back as NaN from the woff kerning table; treat those as none.
    if (Number.isFinite(kern)) pen += kern * scale
  })
  return { glyphs, positions, width: pen }
}

const advance = (face, value, size) => glyphRun(face, value, size).width

/**
 * One glyph's outline as SVG path data, scaled from font units. Built from the
 * raw outline because opentype.js 2.0's Glyph.getPath returns NaN coordinates
 * once the same glyph has been drawn at a different size.
 */
function glyphPathData(glyph, x, y, scale) {
  const px = (v) => (x + v * scale).toFixed(2)
  const py = (v) => (y - v * scale).toFixed(2)
  return glyph.path.commands
    .map((c) => {
      switch (c.type) {
        case 'M':
        case 'L':
          return `${c.type}${px(c.x)} ${py(c.y)}`
        case 'Q':
          return `Q${px(c.x1)} ${py(c.y1)} ${px(c.x)} ${py(c.y)}`
        case 'C':
          return `C${px(c.x1)} ${py(c.y1)} ${px(c.x2)} ${py(c.y2)} ${px(c.x)} ${py(c.y)}`
        default:
          return 'Z'
      }
    })
    .join('')
}

const text = (face, value, x, y, size, fill, anchor = 'start') => {
  const run = glyphRun(face, value, size)
  const left = anchor === 'end' ? x - run.width : x
  const scale = size / face.unitsPerEm
  const d = run.glyphs
    .map((glyph, i) => glyphPathData(glyph, left + run.positions[i], y, scale))
    .join('')
  return { width: run.width, svg: `<path d="${d}" fill="${fill}"/>` }
}

// The icon, without its XML prolog, comments or outer <svg>.
const icon = readFileSync(join(ROOT, 'build', 'icon.svg'), 'utf8')
  .replace(/<\?xml[^>]*>/, '')
  .replace(/<!--[\s\S]*?-->/g, '')
  .replace(/<svg[^>]*>/, '')
  .replace(/<\/svg>/, '')
  .replace(/<title>[^<]*<\/title>/, '')
  .trim()

const parts = []
parts.push(text(bold, 'elecdex', 464, 270, 96, '#000000').svg)
parts.push(text(semibold, 'Sci-fi terminal & system monitor, rebuilt', 474, 350, 34, SLATE_600).svg)

// Feature pills, left to right; the second is highlighted, as on the other cards.
const PILLS = ['Modern', 'eDEX-UI rewrite', 'Terminal', 'System monitor', 'Themes']
const PILL_Y = 410
const PILL_H = 48
const PAD = 22
const GAP = 12
let x = 460
PILLS.forEach((label, i) => {
  const highlighted = i === 1
  const width = advance(semibold, label, 20) + PAD * 2
  parts.push(
    `<rect x="${x}" y="${PILL_Y}" width="${width.toFixed(1)}" height="${PILL_H}" rx="24" fill="${highlighted ? '#e0f2fe' : '#f1f5f9'}"/>`,
  )
  parts.push(text(semibold, label, x + PAD, PILL_Y + 32, 20, highlighted ? SKY_700 : SLATE_600).svg)
  x += width + GAP
})

parts.push(text(semibold, 'github.com/kurouna/elecdex', 1200, 580, 24, SLATE_400, 'end').svg)

const svg = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/gen-repo-card.mjs - edit that, not this. -->
<svg width="1280" height="640" viewBox="0 0 1280 640" xmlns="http://www.w3.org/2000/svg" role="img">
  <title>elecdex - Sci-fi terminal and system monitor, rebuilt</title>
  <rect width="1280" height="640" fill="#ffffff"/>
  <circle cx="1180" cy="-50" r="300" fill="#f0f9ff"/>
  <circle cx="1250" cy="80" r="200" fill="#e0f2fe" fill-opacity="0.6"/>
  <g transform="translate(78.48 140) scale(1.40625)">
    ${icon}
  </g>
  ${parts.join('\n  ')}
</svg>
`

writeFileSync(join(ROOT, 'public', 'elecdex_repo_card.svg'), svg)
console.log(
  `wrote public/elecdex_repo_card.svg (${(svg.length / 1024).toFixed(1)} kB), pills end at x=${x.toFixed(0)}`,
)
