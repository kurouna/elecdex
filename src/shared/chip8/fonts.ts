/** Which small and big glyphs each style has; a style without big digits leaves zeros. */
const STYLES: Readonly<Record<FontStyle, { small: Small; big: Big | null }>> = {
  octo: { small: 'octo', big: 'octo' },
  vip: { small: 'vip', big: null },
  dream6800: { small: 'dream6800', big: null },
  eti660: { small: 'eti660', big: null },
  // SUPER-CHIP's big font has the ten digits only; its letters are blank.
  schip: { small: 'octo', big: 'schip' },
  fish: { small: 'fish', big: 'fish' },
}

/** The bytes to place at SMALL_FONT_AT: the small font and then the big one. */
export function fontBytes(style: FontStyle): Uint8Array {
  const { small, big } = STYLES[style]
  const bytes = new Uint8Array(16 * (SMALL_GLYPH_BYTES + BIG_GLYPH_BYTES))
  bytes.set(SMALL[small], 0)
  if (big !== null) bytes.set(BIG[big], BIG_FONT_AT - SMALL_FONT_AT)
  return bytes
}
